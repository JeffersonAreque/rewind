"""Writes the replay tests of a generated app from flows.json and the app spec.

No model is involved: every step of the recording becomes a step to replay,
and the observations (status, balance, row counts, enabled buttons) become
checks. Steps a modernization change made unnecessary are marked "absorbed"
with the change that explains it, never dropped silently.
"""

import json
import re
import shutil
from pathlib import Path

from rewind.agents.screens import normalize
from rewind.builder.spec import absorbed_steps, slug

TEMPLATE = Path(__file__).resolve().parent / "replay"
COUNT = re.compile(r"^\s*(\d+)")


def observation_checks(observation: dict) -> list[dict]:
    """What to assert after (and before) the steps of a pair, from one observation."""
    subject, before, after = observation["subject"], observation["before"], observation["after"]
    words = normalize(subject)
    if "STATUS BAR" in words:
        return []  # the modern app has no status bar
    if words.endswith(" ROWS") and COUNT.match(after):
        return [{"kind": "row_count", "table": subject[: -len(" rows")].strip(), "count": int(COUNT.match(after).group(1))}]
    if words.endswith(" BUTTON") and normalize(after) in ("ENABLED", "DISABLED"):
        button = subject[: -len(" button")].strip()
        return [
            {"kind": "button", "button": button, "enabled": normalize(before) == "ENABLED", "when": "before"},
            {"kind": "button", "button": button, "enabled": normalize(after) == "ENABLED"},
        ]
    parts = [p.strip() for p in after.split("|") if p.strip()]
    if parts and all(len(p) <= 60 for p in parts):
        return [{"kind": "text", "texts": parts}]
    return []


def replay_steps(flows: dict, spec: dict) -> list[dict]:
    """The steps of steps.json: flows steps plus absorbed marks and checks."""
    steps = [dict(s) for s in flows["steps"]]
    styles = {normalize(s["legacy"]): (s.get("error_style", "dialog"), s.get("success_style", "dialog"))
              for s in spec["screens"]}
    changes = {c["kind"]: i for i, c in enumerate(spec.get("changes", []), 1)}
    for n, kind in absorbed_steps(steps, styles).items():
        step = steps[n - 1]
        number = changes.get(kind)
        step["absorbed"] = f"{kind} (change {number})" if number else kind

    for obs in flows["observations"]:
        mine = [s for s in steps if obs["from"] <= s["frame_from"] < obs["to"]]
        if not mine:
            continue
        for c in observation_checks(obs):
            when = c.pop("when", "after")
            target = mine[0] if when == "before" else mine[-1]
            target.setdefault(when, []).append(c)

    keep = ("n", "screen", "action", "target", "element", "value", "code", "confidence", "variants",
            "frame_from", "frame_to", "time_from", "time_to", "absorbed", "before", "after")
    return [{k: s[k] for k in keep if s.get(k) not in (None, [], "")} for s in steps]


def function_name(name: str, taken: set[str]) -> str:
    base = "test_" + slug(name).replace("-", "_")
    name, i = base, 2
    while name in taken:
        name, i = f"{base}_{i}", i + 1
    taken.add(name)
    return name


def one_line(text) -> str:
    """Safe inside a generated docstring or comment."""
    return " ".join(str(text).split()).replace("\\", "/").replace('"""', "'''")


def module_source(flows: dict, steps: list[dict]) -> str:
    lines = [
        '"""Replay of the legacy recording on the new app: one test per business workflow.',
        "",
        "Generated by Rewind from flows.json and spec.json. Regenerate it with",
        "`python -m rewind build` instead of editing it.",
        '"""',
        "",
        "from replay import load_steps, replay",
        "",
        "STEPS = load_steps()",
    ]
    taken: set[str] = set()
    by_n = {s["n"]: s for s in steps}
    for wf in flows["workflows"]:
        first, last = min(wf["steps"]), max(wf["steps"])
        notes = [f"step {n}: {by_n[n]['target']} = {by_n[n].get('value')!r} has {by_n[n]['confidence']} confidence"
                 for n in wf["steps"] if by_n.get(n, {}).get("confidence") == "low"]
        absorbed = [f"step {n} absorbed by {by_n[n]['absorbed']}" for n in wf["steps"] if by_n.get(n, {}).get("absorbed")]
        lines += [
            "",
            "",
            f"def {function_name(wf['name'], taken)}(app, page):",
            f'    """{one_line(wf["name"])}: steps {first}-{last}. {one_line(wf.get("goal", ""))}"""',
            *[f"    # {one_line(note)}" for note in notes + absorbed],
            f"    replay(page, app, STEPS, first={first}, last={last})",
        ]
    return "\n".join(lines) + "\n"


def write_tests(app_dir: Path, flows: dict, spec: dict) -> list[dict]:
    """Write tests/ in the app folder. Returns the replay steps."""
    tests = app_dir / "tests"
    tests.mkdir(parents=True, exist_ok=True)
    for name in ("replay.py", "conftest.py"):
        shutil.copy(TEMPLATE / name, tests / name)
    steps = replay_steps(flows, spec)
    (tests / "steps.json").write_text(json.dumps(steps, ensure_ascii=False, indent=1), encoding="utf-8")
    (tests / "test_workflows.py").write_text(module_source(flows, steps), encoding="utf-8")
    return steps
